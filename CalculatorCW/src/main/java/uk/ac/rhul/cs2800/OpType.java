package uk.ac.rhul.cs2800;

/**
 * By Dave Cohen, taken from moodle (calculator provided in CW2 description). Representing types of
 * operations supported by calculator.
 * 
 * @author abdul
 */
public enum OpType {
  /**
   * Represents standard infix notation for arithmetic expressions.
   */
  STANDARD,
  /**
   * Represents reverse Polish (postfix) notation for arithmetic expressions.
   */
  REV_POLISH
}
